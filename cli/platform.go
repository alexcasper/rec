package main

import (
	"context"
	"fmt"
	"os"
	"os/exec"
	"runtime"
	"strconv"
	"strings"
	"time"
)

func command(name string, args ...string) (string, error) {
	ctx, cancel := context.WithTimeout(context.Background(), 10*time.Second)
	defer cancel()
	b, e := exec.CommandContext(ctx, name, args...).Output()
	return strings.TrimSpace(string(b)), e
}

func preflight(m Manifest) error {
	switch {
	case runtime.GOOS == "darwin" && runtime.GOARCH == "arm64":
		return preflightDarwin(m)
	case runtime.GOOS == "linux" && runtime.GOARCH == "amd64":
		return preflightLinux(m)
	default:
		return fmt.Errorf("rec supports darwin/arm64 (metal) and linux/amd64 (cpu, rocm); this machine is %s/%s", runtime.GOOS, runtime.GOARCH)
	}
}

func preflightDarwin(m Manifest) error {
	s, err := command("/usr/sbin/sysctl", "-n", "hw.memsize")
	if err != nil {
		return err
	}
	ram, err := strconv.ParseInt(s, 10, 64)
	if err != nil {
		return err
	}
	if ram < m.MinRAM {
		return fmt.Errorf("this model requires %d GiB of memory; detected %d GiB", m.MinRAM>>30, ram>>30)
	}
	if m.Model != "flint" {
		return nil
	}
	chip, err := command("/usr/sbin/sysctl", "-n", "machdep.cpu.brand_string")
	if err != nil {
		return err
	}
	return checkAppleChip(chip)
}

// preflightLinux checks the memory floor reported by /proc/meminfo. The Apple
// chip probe does not apply on Linux; the manifest's backend field decides
// which runtime (cpu, rocm) the bundle carries.
func preflightLinux(m Manifest) error {
	ram, err := linuxMemoryBytes()
	if err != nil {
		return err
	}
	if ram < m.MinRAM {
		return fmt.Errorf("this model requires %d GiB of memory; detected %d GiB", m.MinRAM>>30, ram>>30)
	}
	return nil
}

func linuxMemoryBytes() (int64, error) {
	data, err := os.ReadFile("/proc/meminfo")
	if err != nil {
		return 0, err
	}
	for _, line := range strings.Split(string(data), "\n") {
		if strings.HasPrefix(line, "MemTotal:") {
			fields := strings.Fields(line)
			if len(fields) < 2 {
				break
			}
			kb, err := strconv.ParseInt(fields[1], 10, 64)
			if err != nil {
				return 0, err
			}
			return kb * 1024, nil
		}
	}
	return 0, fmt.Errorf("could not read MemTotal from /proc/meminfo")
}
